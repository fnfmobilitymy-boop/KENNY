"use client";
import { useState } from "react";
import { Button } from "@/components/ui/button";
import { imageAssets } from "@/demo/modules/creative";
import {
  ModuleFrame,
  Panel,
  Editor,
  Select,
  Disconnected,
  Notice,
} from "../shared/module-ui";
import { SampleArt } from "../shared/sample-art";
export function ImageStudio() {
  const [prompt, setPrompt] = useState("");
  const [ratio, setRatio] = useState("1:1");
  const [style, setStyle] = useState("Spatial");
  const [quantity, setQuantity] = useState("1");
  const [filter, setFilter] = useState("All samples");
  const [favorites, setFavorites] = useState<string[]>([]);
  const [selected, setSelected] = useState<string>(imageAssets[0].id);
  const asset = imageAssets.find((a) => a.id === selected)!;
  const visible = imageAssets.filter(
    (a) => filter !== "Favorites" || favorites.includes(a.id),
  );
  return (
    <ModuleFrame
      slug="image-studio"
      tagline="Explore a visual direction. Keep the creative decisions yours."
      related={["website-builder", "video-studio", "marketing"]}
    >
      <div className="tool-three">
        <Panel title="Creative direction" kicker="UNSAVED INPUT">
          <Editor label="Image prompt" value={prompt} onChange={setPrompt} />
          <Select
            label="Aspect ratio"
            value={ratio}
            onChange={setRatio}
            options={["1:1", "16:9", "9:16", "4:3"]}
          />
          <Select
            label="Style preset"
            value={style}
            onChange={setStyle}
            options={["Spatial", "Editorial", "Minimal"]}
          />
          <Select
            label="Output quantity"
            value={quantity}
            onChange={setQuantity}
            options={["1", "2", "4"]}
          />
          <Disconnected
            action="Generate images"
            reason="No image model is connected. Your settings do not generate or alter these fixed assets."
          />
          <Notice>
            Draft: {quantity} × {ratio} · {style}. Not submitted.
          </Notice>
        </Panel>
        <Panel
          title="Sample asset library"
          kicker="HAND-AUTHORED VECTOR STUDIES"
        >
          <Select
            label="Gallery filter"
            value={filter}
            onChange={setFilter}
            options={["All samples", "Favorites"]}
          />
          {visible.length ? (
            <div className="image-gallery">
              {visible.map((a) => (
                <button
                  className="image-tile"
                  key={a.id}
                  aria-pressed={selected === a.id}
                  onClick={() => setSelected(a.id)}
                >
                  <SampleArt
                    name={a.name}
                    palette={a.palette}
                    variant={imageAssets.indexOf(a)}
                  />
                  <span>
                    {a.name}
                    <small> · Fixed sample</small>
                  </span>
                </button>
              ))}
            </div>
          ) : (
            <div className="tool-empty">
              <h3>No favorite samples yet.</h3>
              <p>Select a sample and add a local favorite to see it here.</p>
              <Button variant="ghost" onClick={() => setFilter("All samples")}>
                Show all samples
              </Button>
            </div>
          )}
        </Panel>
        <Panel title="Asset detail" kicker="SELECTED FIXED SAMPLE">
          <SampleArt
            name={asset.name}
            palette={asset.palette}
            variant={imageAssets.indexOf(asset)}
          />
          <h3>{asset.name}</h3>
          <p>
            {asset.detail}. This illustration is not generated by your prompt.
          </p>
          <p>
            Style: {asset.style}
            <br />
            Format: Inline vector illustration
          </p>
          <Button
            variant="secondary"
            aria-pressed={favorites.includes(asset.id)}
            onClick={() =>
              setFavorites((old) =>
                old.includes(asset.id)
                  ? old.filter((id) => id !== asset.id)
                  : [...old, asset.id],
              )
            }
          >
            {favorites.includes(asset.id)
              ? "Remove local favorite"
              : "Add local favorite"}
          </Button>
          <Notice>
            {favorites.length} local favorites · Cleared when leaving this
            module.
          </Notice>
        </Panel>
      </div>
    </ModuleFrame>
  );
}
